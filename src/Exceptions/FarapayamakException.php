    /**
     * Create an exception with a translated Persian message.
     */
    public static function fromCode(int|string $code, ?string $rawMessage = null): self
    {
        $codeStr = (string) $code;
        $description = self::$errorMessages[$codeStr] ?? ($rawMessage ?: "خطای ناشناخته از سامانه فراپیامک با کد {$codeStr}");

        return new self("خطای فراپیامک [کد {$codeStr}]: {$description}", is_numeric($code) ? (int) $code : 0);
    }

    /**
     * Get the descriptive text for a given status code.
     */
    public static function getMessageForCode(int|string $code): string
    {
        $codeStr = (string) $code;
        return self::$errorMessages[$codeStr] ?? "کد بازگشتی: {$codeStr}";
    }
